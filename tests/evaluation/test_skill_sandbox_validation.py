"""
tests/evaluation/test_skill_sandbox_validation.py

WHAT THIS IS FOR:
E2E evaluation test for skill sandbox validation before promotion.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from friday.skills.sandbox import SkillSandbox
from friday.learning.distiller import SkillCandidate


class MockSkill:
    def __init__(self, name: str, procedure: list[dict], required_capabilities: list[str], risk_profile: str = "GREEN"):
        self.name = name
        self.procedure = procedure
        self.required_capabilities = required_capabilities
        self.risk_profile = risk_profile


class TestSkillSandboxValidation:
    @pytest.fixture
    def sandbox(self, tmp_path):
        return SkillSandbox(
            workspace_dir=tmp_path,
            allowed_capabilities=["filesystem", "computer"],
            timeout_seconds=10,
        )

    def test_rejects_red_risk_skill(self, sandbox):
        """RED risk skills should be rejected in sandbox validation."""
        skill = MockSkill(
            name="shutdown_computer",
            procedure=[{"action": "system.shutdown", "args": {}}],
            required_capabilities=["system"],
            risk_profile="RED",
        )
        result = sandbox.validate_skill(skill)
        assert result.valid is False
        assert any("RED risk profile" in e for e in result.errors)

    def test_accepts_green_risk_skill(self, sandbox):
        """GREEN risk skills with allowed capabilities should pass."""
        skill = MockSkill(
            name="read_file",
            procedure=[{"action": "filesystem.read", "args": {"path": "test.txt"}}],
            required_capabilities=["filesystem"],
            risk_profile="GREEN",
        )
        result = sandbox.validate_skill(skill)
        assert result.valid is True

    def test_skill_candidate_can_be_validated(self, tmp_path):
        """SkillCandidate generated by distiller should be validatable."""
        sandbox = SkillSandbox(tmp_path, ["filesystem", "system"])

        candidate = SkillCandidate(
            proposed_name="test_workflow",
            purpose="Test workflow",
            triggers=["test workflow"],
            prerequisites=["System online"],
            required_capabilities=["filesystem"],
            risk_profile="GREEN",
            inputs=[],
            procedure=[{"action": "filesystem.read", "arguments": {"path": "{var0}"}}],
            expected_observations=["File read"],
            verification=[{"check": "ok"}],
            failure_modes=["error"],
            recovery=[{"on_failure": "retry"}],
            source_trajectory_ids=["traj_1"],
        )

        # Convert to Skill-compatible object
        skill = MockSkill(
            name=candidate.proposed_name,
            procedure=[{"action": "filesystem.read", "args": {"path": "test.txt"}}],
            required_capabilities=candidate.required_capabilities,
            risk_profile=candidate.risk_profile,
        )

        result = sandbox.validate_skill(skill)
        assert result.valid is True